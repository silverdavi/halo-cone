def mass_fractions(isotopes):
    weights = np.array([n * A for A, _Z, n in isotopes], dtype=float)
    weights /= weights.sum()
    return [
        (A, Z, n, float(w))
        for (A, Z, n), w in zip(isotopes, weights)
    ]


def helm2(E_keV, A):
    E = np.asarray(E_keV, dtype=float)
    m_MeV = A * 931.494
    q = np.sqrt(np.maximum(2.0 * m_MeV * (E * 1e-3), 0.0)) / HBARC
    a, s = 0.52, 0.9
    c = 1.23 * A ** (1.0 / 3.0) - 0.60
    R = np.sqrt(max(c * c + (7.0 / 3.0) * np.pi**2 * a * a - 5.0 * s * s, 0.0))
    x = q * R
    sph = np.empty_like(x)
    small = x < 1e-3
    sph[small] = 1.0 - x[small] ** 2 / 10.0
    xs = x[~small]
    sph[~small] = 3.0 * (np.sin(xs) - xs * np.cos(xs)) / xs**3
    return (sph * np.exp(-0.5 * (q * s) ** 2)) ** 2


def vmin_kms(E_keV, m_chi, A):
    E = np.asarray(E_keV, dtype=float)
    m_N = A * AMU
    mu = m_chi * m_N / (m_chi + m_N)
    beta2 = m_N * (E * 1e-6) / (2.0 * mu * mu)
    return np.sqrt(np.maximum(beta2, 0.0)) * C_KM


def load_flux(name):
    raw = np.loadtxt(FLUX_DIR / f"{name}.txt", delimiter=",")
    raw = raw[np.isfinite(raw).all(axis=1)]
    raw = raw[(raw[:, 0] > 0) & (raw[:, 1] > 0)]
    # Files are shape-normalized. Renormalize in case of the sentinel rows.
    area = np.trapezoid(raw[:, 1], raw[:, 0])
    if len(raw) == 1:
        return raw[:, 0], raw[:, 1], True
    raw[:, 1] /= area
    return raw[:, 0], raw[:, 1], False


def cevns_spectrum(E_keV, A, Z, flux_name):
    """Events per tonne per year per keV for a pure isotope."""
    E = np.asarray(E_keV, dtype=float)
    phi_tot, frac_unc, _mono_flag = SOLAR[flux_name]
    E_nu, shape, is_mono = load_flux(flux_name)
    N = A - Z
    Qw = N - (1.0 - 4.0 * SIN2_THETA_W) * Z
    m_N = AMU * A
    m_N_keV = m_N * 1e6
    prefac = (
        (G_F**2 / (4.0 * np.pi))
        * Qw**2
        * m_N
        * (0.197e-13) ** 2
        * 1e-6
        * 1000.0
        / A
        * N_A
    )
    if is_mono or len(E_nu) == 1:
        Enu = float(E_nu[0])
        kin = 1.0 - (m_N_keV * E) / (2.0 * (Enu * 1000.0) ** 2)
        kin = np.clip(kin, 0.0, None)
        dsig = prefac * kin * phi_tot
    else:
        Enu = E_nu
        flux = shape * phi_tot  # cm^-2 s^-1 MeV^-1
        kin = 1.0 - (m_N_keV * E[:, None]) / (2.0 * (Enu[None, :] * 1000.0) ** 2)
        kin = np.clip(kin, 0.0, None)
        integrand = prefac * kin * flux[None, :]
        dsig = np.trapezoid(integrand, Enu, axis=1)
    dsig = dsig * helm2(E, A)
    return dsig * 1000.0 * SEC_PER_YEAR, frac_unc


def compound_spectrum(E, isotopes, flux_name, mass_fraction_of_element=1.0):
    total = np.zeros_like(E, dtype=float)
    unc = SOLAR[flux_name][1]
    fracs = mass_fractions(isotopes)
    for A, Z, _n, w in fracs:
        dR, unc = cevns_spectrum(E, A, Z, flux_name)
        total += mass_fraction_of_element * w * dR
    return total, unc


def load_yield():
    def grab(kind, which):
        with open(XE_DATA / "signal" / f"{kind}_ybe_model_{which}.json") as f:
            d = json.load(f)
        return np.asarray(d["coordinate_system"], float), np.asarray(d["map"], float)

    out = {}
    for kind in ("ly", "qy"):
        for which in ("lower", "median", "upper"):
            out[f"{kind}_{which}"] = grab(kind, which)
    return out


def yield_curve(yields, kind, t):
    E, med = yields[f"{kind}_median"]
    _E, lo = yields[f"{kind}_lower"]
    _E, up = yields[f"{kind}_upper"]
    if t >= 0:
        y = med + (up - med) * t
    else:
        y = med + (lo - med) * (-t)  # t is negative; release uses (lower-median)*t
        # get_yield: t<0 -> median + (lower-median)*t = median - (median-lower)*|t|
        y = med + (lo - med) * t
    return interp1d(E, np.clip(y, 1.0, 10.0), bounds_error=False, fill_value=(y[0], y[-1]))


def load_mono_grid():
    cache = OUT / "mono_grid.npz"
    if cache.exists():
        z = np.load(cache, allow_pickle=False)
        return (
            z["energies"],
            z["ly"],
            z["qy"],
            z["grid_sr0"],
            z["grid_sr1"],
            z["bins_sr0"],
            z["bins_sr1"],
        )
    basis = XE_DATA / "orthonormal_basis"
    files = sorted(basis.glob("template_XENONnT_sr*_recasting_mono_*.h5"))
    parsed = []
    for p in files:
        m = MONO_RE.search(p.name)
        if not m:
            continue
        sr, a, b, ly, qy = m.groups()
        energy = float(f"{a}.{b}")
        parsed.append((sr, energy, int(ly), int(qy), p))
    # SR1 has no 0.5 keV anchor; the analysis ROI starts at 0.51 keV.
    energies_by_sr = {}
    for sr, energy, _ly, _qy, _p in parsed:
        energies_by_sr.setdefault(sr, set()).add(energy)
    common = set.intersection(*energies_by_sr.values())
    energies = np.array(sorted(common))
    lys = np.array(sorted({ly for _sr, e, ly, _qy, _p in parsed if e in common}))
    qys = np.array(sorted({qy for _sr, e, _ly, qy, _p in parsed if e in common}))
    e_index = {e: i for i, e in enumerate(energies)}
    ly_index = {int(v): i for i, v in enumerate(lys)}
    qy_index = {int(v): i for i, v in enumerate(qys)}

    def bins_of(path):
        with h5py.File(path, "r") as f:
            return [np.array(f["bins"][str(i)]) for i in range(4)]

    sample = {sr: next(p for s, _e, _ly, _qy, p in parsed if s == sr) for sr in ("sr0", "sr1")}
    bins = {sr: bins_of(sample[sr]) for sr in ("sr0", "sr1")}
    grids = {
        sr: np.zeros((len(energies), len(lys), len(qys), 81))
        for sr in ("sr0", "sr1")
    }
    filled = {sr: np.zeros((len(energies), len(lys), len(qys)), dtype=bool) for sr in ("sr0", "sr1")}
    for i, (sr, energy, ly, qy, path) in enumerate(parsed):
        if energy not in e_index:
            continue
        with h5py.File(path, "r") as f:
            h = np.array(f["templates"]["template"], dtype=float).ravel()
        grids[sr][e_index[energy], ly_index[ly], qy_index[qy]] = h
        filled[sr][e_index[energy], ly_index[ly], qy_index[qy]] = True
        if i % 800 == 0:
            print(f"  loaded {i}/{len(parsed)} mono templates", flush=True)
    if not filled["sr0"].all() or not filled["sr1"].all():
        raise RuntimeError("mono-energetic grid is missing entries")
    np.savez(
        cache,
        energies=energies,
        ly=lys.astype(float),
        qy=qys.astype(float),
        grid_sr0=grids["sr0"],
        grid_sr1=grids["sr1"],
        bins_sr0=np.vstack(bins["sr0"]),
        bins_sr1=np.vstack(bins["sr1"]),
    )
    return energies, lys.astype(float), qys.astype(float), grids["sr0"], grids["sr1"], np.vstack(bins["sr0"]), np.vstack(bins["sr1"])


def response_on_grid(energies, ly_axis, qy_axis, grid, E_query, ly_of_E, qy_of_E):
    interp = RegularGridInterpolator(
        (energies, ly_axis, qy_axis),
        grid,
        bounds_error=False,
        fill_value=None,
    )
    ly = np.clip(ly_of_E(E_query), 1.0, 10.0)
    qy = np.clip(qy_of_E(E_query), 1.0, 10.0)
    # Clamp energy into the tabulated recoil window.
    Eq = np.clip(E_query, energies[0], energies[-1])
    pts = np.column_stack([Eq, ly, qy])
    return interp(pts)


def released_response(energies, ly_axis, qy_axis, g0, g1, E, ly, qy):
    """Expected counts per tonne-year of total exposure in the SR0+SR1 observable.

    Each release template is normalised per tonne-year of its own science run,
    so a tonne-year of combined exposure is split by the release livetimes
    (1.174 : 2.343). Without this weighting the 8B rate comes out as 6.9/t y
    instead of the published 3.4/t y.
    """
    tot = SR_LIVETIME["sr0"] + SR_LIVETIME["sr1"]
    f0, f1 = SR_LIVETIME["sr0"] / tot, SR_LIVETIME["sr1"] / tot
    return np.hstack([f0 * response_on_grid(energies, ly_axis, qy_axis, g0, E, ly, qy),
                      f1 * response_on_grid(energies, ly_axis, qy_axis, g1, E, ly, qy)])


def spectrum_from_release(path):
    with open(path) as f:
        d = json.load(f)
    E = np.asarray(d["map"], float)
    cdf = np.asarray(d["coordinate_system"], float)
    # Release stores a CDF. Differentiate, then restore the quoted integral.
    dcdf = np.gradient(cdf, E)
    dcdf = np.clip(dcdf, 0.0, None)
    area = np.trapezoid(dcdf, E)
    dR = d["rate"] * dcdf / area
    return E, dR, float(d["rate"])


def fold_spectrum(E_src, dR_src, E_grid, T_grid):
    """Expected histogram for a differential rate (events/tonne/year/keV)."""
    dR = np.interp(E_grid, E_src, dR_src, left=0.0, right=0.0)
    dE = np.diff(E_grid)
    piece = 0.5 * (T_grid[1:] * dR[1:, None] + T_grid[:-1] * dR[:-1, None]) * dE[:, None]
    return piece.sum(axis=0)


def load_template(path):
    with h5py.File(path, "r") as f:
        return np.array(f["templates"]["template"], dtype=float).ravel()


def cosine(a, b):
    na, nb = np.linalg.norm(a), np.linalg.norm(b)
    if na == 0 or nb == 0:
        return 0.0
    return float(np.dot(a, b) / (na * nb))


def cumtrapz_weighted(T, E, K):
    """Cumulative integral of T(E)*K(E) from the left edge. Shape (nE, nB)."""
    dE = np.diff(E)
    piece = 0.5 * (
        T[1:] * K[1:, None] + T[:-1] * K[:-1, None]
    ) * dE[:, None]
    out = np.zeros_like(T)
    out[1:] = np.cumsum(piece, axis=0)
    return out


def stream_matrix(E, T, m_chi, isotopes, element_mass_fraction, v_grid):
    """Columns are mono-speed observable spectra, one per v in v_grid.

    Weights absorb the free cross section. Isotope and stoichiometry
    weights keep the relative rate physical.
    """
    nB = T.shape[1]
    G = np.zeros((nB, len(v_grid)))
    fracs = mass_fractions(isotopes)
    for A, _Z, _n, w in fracs:
        K = element_mass_fraction * w * (A**2) * helm2(E, A)
        vmin = vmin_kms(E, m_chi, A)
        C = cumtrapz_weighted(T, E, K)
        # vmin increases with E. Last index with vmin(E) <= v.
        idx = np.searchsorted(vmin, v_grid, side="right") - 1
        valid = idx >= 0
        G[:, valid] += C[idx[valid]].T
    return G


def project(G, phi):
    """Euclidean projection of phi onto {G x : x >= 0}. Returns residual fraction."""
    phi = np.asarray(phi, float)
    nrm = np.linalg.norm(phi)
    if nrm == 0:
        return dict(residual=0.0, x=np.zeros(G.shape[1]), recon=phi.copy(), deviance=0.0)
    col = np.linalg.norm(G, axis=0)
    keep = col > 1e-14 * col.max() if col.max() > 0 else np.zeros(len(col), dtype=bool)
    if not np.any(keep):
        return dict(
            residual=1.0,
            x=np.zeros(G.shape[1]),
            recon=np.zeros_like(phi),
            deviance=poisson_deviance(phi, np.zeros_like(phi)),
            inaccessible=True,
        )
    x_red, _ = nnls(G[:, keep], phi)
    x = np.zeros(G.shape[1])
    x[keep] = x_red
    recon = G @ x
    resid = np.linalg.norm(phi - recon) / nrm
    return dict(
        residual=float(resid),
        x=x,
        recon=recon,
        deviance=float(poisson_deviance(phi, recon)),
        cosine=cosine(phi, recon),
        inaccessible=False,
    )


def poisson_deviance(mu, muhat):
    mu = np.asarray(mu, float)
    muhat = np.maximum(np.asarray(muhat, float), 0.0)
    muhat_safe = np.maximum(muhat, 1e-300)
    out = np.empty_like(mu)
    zero = mu <= 0
    out[zero] = muhat[zero]
    nz = ~zero
    out[nz] = mu[nz] * np.log(mu[nz] / muhat_safe[nz]) - (mu[nz] - muhat[nz])
    return float(2.0 * np.sum(out))


def load_eff_table(path):
    rows = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        a, b = line.split()
        rows.append((float(a), float(b)))
    arr = np.array(rows, float)
    return arr[:, 0], arr[:, 1]


def cresst_efficiencies(E):
    Ec, cut = load_eff_table(CRESST_DIR / "C3P1_DetA_cuteff.dat")
    cut_i = np.interp(E, Ec, cut, left=0.0, right=cut[-1])
    out = {}
    for name, fn in (("O", "O"), ("Ca", "Ca"), ("W", "W")):
        Ee, acc = load_eff_table(CRESST_DIR / f"C3P1_DetA_eff_AR_{fn}.dat")
        acc_i = np.interp(E, Ee, acc, left=0.0, right=acc[-1])
        eff = cut_i * acc_i
        eff[E < CRESST_THRESHOLD] = 0.0
        eff[E > CRESST_EMAX] = 0.0
        out[name] = eff
    return out


def bin_rates(E, dR, edges):
    """Integrate dR over bins. E and dR are fine samples."""
    # cumulative integral
    c = np.zeros(len(E))
    c[1:] = np.cumsum(0.5 * (dR[1:] + dR[:-1]) * np.diff(E))
    cdf = interp1d(E, c, bounds_error=False, fill_value=(0.0, c[-1]))
    return cdf(edges[1:]) - cdf(edges[:-1])


def main():
    print("Loading XENONnT mono-energetic response grid...", flush=True)
    energies, ly_axis, qy_axis, g0, g1, bins0, bins1 = load_mono_grid()
    yields = load_yield()
    ly = yield_curve(yields, "ly", 0.0)
    qy = yield_curve(yields, "qy", 0.0)
    E = np.linspace(E_ROI[0], E_ROI[1], 241)
    print("Interpolating median-yield response...", flush=True)
    T0 = response_on_grid(energies, ly_axis, qy_axis, g0, E, ly, qy)
    T1 = response_on_grid(energies, ly_axis, qy_axis, g1, E, ly, qy)
    T = np.hstack([T0, T1])  # (nE, 162)

    # --- validation: fold the released recoil spectra into the released histograms
    print("Folding released spectra through the mono-energy basis...", flush=True)
    validation = {}
    for label, fname in (
        ("b8", "cevns_spectrum.json"),
        ("wimp6", "wimp_si_spectrum_6.json"),
        ("wimp3", "wimp_si_spectrum_3.json"),
        ("wimp12", "wimp_si_spectrum_12.json"),
    ):
        Es, dR, rate = spectrum_from_release(XE_DATA / "signal" / fname)
        folded = fold_spectrum(Es, dR, E, T)
        if label == "b8":
            ref = np.concatenate(
                [
                    load_template(XE_DATA / "b8" / f"template_XENONnT_{sr}_b8_cevns_tly_0.0_tqy_0.0.h5")
                    for sr in ("sr0", "sr1")
                ]
            )
        else:
            mass = fname.split("_")[-1].replace(".json", "")
            ref = np.concatenate(
                [
                    load_template(
                        XE_DATA
                        / "wimp_si"
                        / f"template_XENONnT_{sr}_wimp_si_{mass}_cevns_tly_0.0_tqy_0.0.h5"
                    )
                    for sr in ("sr0", "sr1")
                ]
            )
        scale = float(np.dot(folded, ref) / np.dot(folded, folded)) if np.dot(folded, folded) else 0.0
        validation[label] = dict(
            rate_per_ty=rate,
            cosine=cosine(folded, ref),
            cosine_after_scale=cosine(scale * folded, ref),
            best_scale_ty=scale,
            folded_sum=float(folded.sum()),
            reference_sum=float(ref.sum()),
            sr_livetimes=SR_LIVETIME,
        )
        print(
            f"  {label}: cosine={validation[label]['cosine']:.4f} "
            f"scale={scale:.3f} folded_sum={folded.sum():.3f} ref_sum={ref.sum():.3f}",
            flush=True,
        )

    b8_ref = np.concatenate(
        [
            load_template(XE_DATA / "b8" / f"template_XENONnT_{sr}_b8_cevns_tly_0.0_tqy_0.0.h5")
            for sr in ("sr0", "sr1")
        ]
    )
    # Per-tonne-year neutrino histogram implied by the release.
    # best_scale from the fold is the exposure that converts a per-ty fold into the template.
    exposure_ty = validation["b8"]["best_scale_ty"]
    phi_xe = b8_ref / exposure_ty

    # Yield-morph shape scatter of the released 8B templates, |t_ly| or |t_qy| = 1.
    morph = []
    med_hat = b8_ref / np.linalg.norm(b8_ref)
    for tly in (-1, 0, 1):
        for tqy in (-1, 0, 1):
            if tly == 0 and tqy == 0:
                continue
            v = np.concatenate(
                [
                    load_template(
                        XE_DATA
                        / "b8"
                        / f"template_XENONnT_{sr}_b8_cevns_tly_{tly}.0_tqy_{tqy}.0.h5"
                    )
                    for sr in ("sr0", "sr1")
                ]
            )
            v_hat = v / np.linalg.norm(v)
            morph.append(float(np.linalg.norm(v_hat - med_hat)))
    yield_shape_radius = float(np.median(morph))

    # Background templates at median yield, for the angle between 8B and radiogenic NR.
    backgrounds = {}
    for name, path0, path1 in (
        (
            "ac",
            XE_DATA / "ac" / "template_XENONnT_sr0_ac_cevns.h5",
            XE_DATA / "ac" / "template_XENONnT_sr1_ac_cevns.h5",
        ),
        (
            "er",
            XE_DATA / "er" / "template_XENONnT_sr0_er_cevns.h5",
            XE_DATA / "er" / "template_XENONnT_sr1_er_cevns.h5",
        ),
        (
            "rg",
            XE_DATA / "rg" / "template_XENONnT_sr0_rg_cevns_tly_0.0_tqy_0.0.h5",
            XE_DATA / "rg" / "template_XENONnT_sr1_rg_cevns_tly_0.0_tqy_0.0.h5",
        ),
    ):
        v = np.concatenate([load_template(path0), load_template(path1)])
        backgrounds[name] = dict(
            counts=float(v.sum()),
            cosine_with_b8=cosine(v, b8_ref),
            shape_distance=float(
                np.linalg.norm(v / np.linalg.norm(v) - med_hat)
            ),
        )

    # --- our 8B calculation versus the released recoil spectrum (shape)
    E_check = np.linspace(0.45, 10.0, 400)
    dR_8B, _ = compound_spectrum(E_check, XE_ISOTOPES, "8B")
    Es_rel, dR_rel, rate_rel = spectrum_from_release(XE_DATA / "signal" / "cevns_spectrum.json")
    dR_rel_i = np.interp(E_check, Es_rel, dR_rel)
    # Compare on the analysis ROI, scale-free.
    mroi = (E_check >= E_ROI[0]) & (E_check <= E_ROI[1])
    validation["b8_recoil_shape_cosine"] = cosine(dR_8B[mroi], dR_rel_i[mroi])
    validation["b8_our_integral_0p45_10"] = float(np.trapezoid(dR_8B, E_check))
    validation["b8_release_integral"] = rate_rel
    print(
        f"  8B recoil shape vs release cosine={validation['b8_recoil_shape_cosine']:.4f} "
        f"our_rate={validation['b8_our_integral_0p45_10']:.1f} release_rate={rate_rel:.1f}",
        flush=True,
    )

    # --- cone scan in the released observable
    masses = np.unique(
        np.concatenate(
            [
                np.array([3, 4, 5, 5.5, 6, 8, 10, 12], float),
                np.geomspace(2.0, 30.0, 37),
            ]
        )
    )
    v_grid = np.geomspace(40.0, V_MAX, 90)
    rows = []
    print(f"Projecting 8B onto the SI cone for {len(masses)} masses...", flush=True)
    # Self-test: a random conic combination must project back to ~0.
    G_test = stream_matrix(E, T, 6.0, XE_ISOTOPES, 1.0, v_grid)
    rng = np.random.default_rng(0)
    x_true = rng.random(G_test.shape[1])
    x_true[x_true < 0.7] = 0
    synthetic = G_test @ x_true
    self_test = project(G_test, synthetic)
    print(f"  cone self-test residual={self_test['residual']:.2e}", flush=True)

    # Released WIMP spectra should lie in the cone if the kernel matches the collaboration's.
    wimp_in_cone = {}
    for mass_label, fname in (
        ("6", "wimp_si_spectrum_6.json"),
        ("3", "wimp_si_spectrum_3.json"),
        ("12", "wimp_si_spectrum_12.json"),
    ):
        Es, dR, _rate = spectrum_from_release(XE_DATA / "signal" / fname)
        folded = fold_spectrum(Es, dR, E, T)
        G = stream_matrix(E, T, float(mass_label), XE_ISOTOPES, 1.0, v_grid)
        fit = project(G, folded)
        wimp_in_cone[mass_label] = dict(residual=fit["residual"], cosine=fit.get("cosine"))
        print(f"  released {mass_label} GeV WIMP in cone residual={fit['residual']:.3e}", flush=True)

    G_by_mass = {}
    for m in masses:
        G = stream_matrix(E, T, float(m), XE_ISOTOPES, 1.0, v_grid)
        G_by_mass[float(m)] = G
        fit = project(G, phi_xe)
        # Also the total released counts, for the deviance at the real exposure.
        fit_counts = project(G * exposure_ty, b8_ref)
        rows.append(
            dict(
                mass=float(m),
                residual=fit["residual"],
                cosine=fit.get("cosine", 0.0),
                deviance_per_ty=fit["deviance"],
                deviance_at_exposure=fit_counts["deviance"],
                inaccessible=bool(fit.get("inaccessible", False)),
                predicted_counts=float((fit["recon"] * exposure_ty).sum()),
                n_streams=int(np.count_nonzero(fit["x"] > 1e-8 * fit["x"].max() if fit["x"].max() else 1)),
            )
        )

    # Ideal energy-spectrum cone on the same ROI, no S1/S2 migration.
    # T_ideal bins the ROI into 16 equal bins. Columns use K(E) only.
    edges_ideal = np.linspace(E_ROI[0], E_ROI[1], 17)
    centers = 0.5 * (edges_ideal[:-1] + edges_ideal[1:])
    # Piecewise-constant response: each fine-grid energy contributes to its bin.
    T_ideal = np.zeros((len(E), len(centers)))
    which = np.clip(np.digitize(E, edges_ideal) - 1, 0, len(centers) - 1)
    for i, b in enumerate(which):
        T_ideal[i, b] = 1.0
    dR_8B_roi = np.interp(E, E_check, dR_8B)
    phi_ideal = fold_spectrum(E, dR_8B_roi, E, T_ideal)
    ideal_rows = []
    for m in masses:
        G = stream_matrix(E, T_ideal, float(m), XE_ISOTOPES, 1.0, v_grid)
        fit = project(G, phi_ideal)
        ideal_rows.append(
            dict(mass=float(m), residual=fit["residual"], inaccessible=bool(fit.get("inaccessible", False)))
        )

    # --- CRESST forecast
    print("Building CRESST-III forecast spectra...", flush=True)
    E_c = np.linspace(0.02, 16.0, 2000)
    eff = cresst_efficiencies(E_c)
    # CaWO4 stoichiometry
    M_O, M_Ca, M_W = 15.999 * 4, 40.078, 183.84
    M_tot = M_O + M_Ca + M_W
    stoich = {"O": M_O / M_tot, "Ca": M_Ca / M_tot, "W": M_W / M_tot}
    nuclei = {"O": O_ISOTOPES, "Ca": CA_ISOTOPES, "W": W_ISOTOPES}
    flux_names = list(SOLAR)
    # Fine differential rates per element, efficiency applied, summed over fluxes.
    dR_el = {el: np.zeros_like(E_c) for el in nuclei}
    dR_el_by_flux = {el: {} for el in nuclei}
    for el, isos in nuclei.items():
        for flux in flux_names:
            dR, _unc = compound_spectrum(E_c, isos, flux, stoich[el])
            dR = dR * eff[el]
            dR_el_by_flux[el][flux] = dR
            dR_el[el] += dR
    edges_c = np.geomspace(CRESST_THRESHOLD, CRESST_EMAX, 25)
    # 24 bins. Also keep per-element vectors.
    phi_el = {}
    G_el = {}  # filled per mass later for the worst xenon mass; store generators' ingredients
    for el in nuclei:
        phi_el[el] = bin_rates(E_c, dR_el[el], edges_c).astype(float)
    phi_untagged = sum(phi_el.values())

    # Response in CRESST bins: build T_c such that fold integrates K*Theta into bins
    # with efficiency already inside an effective T that is 1 inside the bin.
    # Efficiency depends on energy, so put it in K via a modified helm path:
    # we'll construct T_c(E_c) as the bin indicator and pass eff*stoich inside a custom matrix.
    which_c = np.clip(np.digitize(E_c, edges_c) - 1, 0, len(edges_c) - 2)
    T_c = np.zeros((len(E_c), len(edges_c) - 1))
    for i, b in enumerate(which_c):
        if edges_c[0] <= E_c[i] < edges_c[-1]:
            T_c[i, b] = 1.0

    def cresst_streams(m_chi, el):
        # Multiply the geometric kernel by the published efficiency.
        # stream_matrix already applies A^2 F^2 and stoichiometry through element_mass_fraction,
        # but not efficiency. Fold efficiency into T.
        T_eff = T_c * eff[el][:, None]
        return stream_matrix(E_c, T_eff, m_chi, nuclei[el], stoich[el], v_grid)

    # Identify xenon-degenerate masses: residual below the yield-morph radius,
    # or below 2%, whichever is the more conservative practical threshold.
    xe_residuals = np.array([r["residual"] for r in rows])
    practical = max(yield_shape_radius, 0.02)
    degenerate_masses = [r["mass"] for r in rows if r["residual"] < practical and not r["inaccessible"]]
    # Always study the mass of minimum residual, even if nothing is fully degenerate.
    i_best = int(np.argmin(xe_residuals))
    focus_masses = sorted(set(degenerate_masses + [rows[i_best]["mass"], 6.0]))

    print(f"Yield-morph shape radius={yield_shape_radius:.4f}", flush=True)
    print(f"Xenon residual range={xe_residuals.min():.4f}..{xe_residuals.max():.4f}", flush=True)
    print(f"Masses below practical threshold {practical:.3f}: {degenerate_masses}", flush=True)

    joint = {}
    for m in focus_masses:
        Gx = G_by_mass[m] if m in G_by_mass else stream_matrix(E, T, m, XE_ISOTOPES, 1.0, v_grid)
        entry = {"mass": m, "xenon_residual": project(Gx, phi_xe)["residual"], "channels": {}}
        for el in list(nuclei) + ["untagged"]:
            if el == "untagged":
                Gs = sum(cresst_streams(m, name) for name in nuclei)
                phi = phi_untagged
            else:
                Gs = cresst_streams(m, el)
                phi = phi_el[el]
            # Rate-space joint vector (events per tonne-year). Equal-exposure identifiability.
            G_joint = np.vstack([Gx, Gs])
            phi_joint = np.concatenate([phi_xe, phi])
            fit = project(G_joint, phi_joint)
            # Bin-by-bin: which single CRESST bin most increases the residual.
            base = entry["xenon_residual"]
            best = None
            bin_residuals = []
            for k in range(Gs.shape[0]):
                if phi[k] <= 0 and np.all(Gs[k] == 0):
                    continue
                fit_k = project(
                    np.vstack([Gx, Gs[k : k + 1]]),
                    np.concatenate([phi_xe, phi[k : k + 1]]),
                )
                rec_k = fit_k["recon"][-1]
                bin_residuals.append(
                    dict(
                        bin=k,
                        E_lo=float(edges_c[k]),
                        E_hi=float(edges_c[k + 1]),
                        residual=fit_k["residual"],
                        delta=fit_k["residual"] - base,
                        neutrino_per_ty=float(phi[k]),
                        best_dm_per_ty=float(rec_k),
                    )
                )
            bin_residuals.sort(key=lambda d: d["delta"], reverse=True)
            # Poisson deviance of this joint fit is numerically unstable when a
            # projected bin undershoots (ill-conditioned stream basis). The
            # exposures quoted in results/finding.json use a column-normalized
            # bounded least-squares fit and the profiled Gaussian statistic.
            fit_xe_counts = project(Gx * exposure_ty, b8_ref)
            # Scan CaWO4 exposure on a log grid. Counts = exposure * rate.
            exposures = np.geomspace(1e-6, 1e3, 80)  # tonne-year
            # Precompute the best DM coefficients from the rate-space fit, then
            # evaluate the Poisson deviance of (xenon counts + cresst counts).
            # Re-fit at each exposure so the halo can trade off the two datasets.
            dev_curve = []
            # Coarser exposure scan with a refit. 24 is enough to interpolate.
            for eps in np.geomspace(1e-5, 100.0, 28):
                fit_e = project(
                    np.vstack([Gx * exposure_ty, Gs * eps]),
                    np.concatenate([b8_ref, phi * eps]),
                )
                dev_curve.append((float(eps), fit_e["deviance"]))
            dev_curve = np.array(dev_curve)
            # Smallest exposure with deviance >= 9. If xenon alone already exceeds 9,
            # the extra exposure is zero.
            if fit_xe_counts["deviance"] >= 9.0:
                eps_star = 0.0
            else:
                above = np.where(dev_curve[:, 1] >= 9.0)[0]
                eps_star = float(dev_curve[above[0], 0]) if len(above) else None
            entry["channels"][el] = dict(
                joint_residual_equal_exposure=fit["residual"],
                xenon_only_residual=base,
                neutrino_events_per_ty=float(phi.sum()),
                top_bins=bin_residuals[:5],
                exposure_ty_for_deviance_9=eps_star,
                deviance_xenon_only=fit_xe_counts["deviance"],
            )
            print(
                f"  m={m:.2f} {el}: joint residual {fit['residual']:.4f} "
                f"(xenon {base:.4f}), top bin {bin_residuals[0]['E_lo']:.3f}-{bin_residuals[0]['E_hi']:.3f} keV "
                f"delta={bin_residuals[0]['delta']:.4f}, eps*={eps_star}",
                flush=True,
            )
        joint[f"{m:.4f}"] = entry

    # v-window overlap at the focus mass nearest 6 GeV, for the design statement.
    m_star = min(focus_masses, key=lambda m: abs(m - 6.0))
    vmin_xe = vmin_kms(np.array(E_ROI), m_star, 131)
    overlap = {}
    for el, isos in nuclei.items():
        A = isos[0][0]
        # bin edges -> vmin
        vlo = vmin_kms(edges_c[:-1], m_star, A)
        vhi = vmin_kms(edges_c[1:], m_star, A)
        overlap[el] = [
            dict(
                E_lo=float(edges_c[k]),
                E_hi=float(edges_c[k + 1]),
                v_lo=float(vlo[k]),
                v_hi=float(vhi[k]),
                overlaps_xenon=bool(vhi[k] >= vmin_xe[0] and vlo[k] <= min(vmin_xe[1], V_MAX)),
            )
            for k in range(len(edges_c) - 1)
        ]

    # Real-data context: counts in the release.
    real_counts = {}
    import pickle

    with open(XE_DATA / "real_data.pkl", "rb") as f:
        real = pickle.load(f)
    real_counts = {"sr0": int(len(real[0])), "sr1": int(len(real[1]))}

    summary = dict(
        halo_class=dict(
            description="nonnegative lab-frame speed distributions supported on [0, v_max]",
            v_esc_kms=V_ESC,
            v_earth_kms=V_EARTH,
            v_max_kms=V_MAX,
        ),
        validation=validation,
        wimp_templates_in_cone=wimp_in_cone,
        cone_self_test_residual=self_test["residual"],
        yield_shape_radius_1sigma=yield_shape_radius,
        practical_degeneracy_threshold=practical,
        backgrounds=backgrounds,
        b8_template_counts=dict(total=float(b8_ref.sum()), per_ty=float(phi_xe.sum())),
        inferred_exposure_ty=exposure_ty,
        real_event_counts=real_counts,
        xenon_scan=[
            dict(
                mass=r["mass"],
                residual=r["residual"],
                deviance_at_exposure=r["deviance_at_exposure"],
                inaccessible=r["inaccessible"],
                n_streams=r["n_streams"],
                ideal_residual=ideal_rows[i]["residual"],
                ideal_inaccessible=ideal_rows[i]["inaccessible"],
            )
            for i, r in enumerate(rows)
        ],
        cresst=dict(
            threshold_keV=CRESST_THRESHOLD,
            emax_keV=CRESST_EMAX,
            baseline_resolution_eV=CRESST_SIGMA_EV,
            exposure_kg_day=CRESST_EXPOSURE_KG_DAY,
            exposure_ty=CRESST_EXPOSURE_KG_DAY / (1000.0 * 365.25),
            stoichiometry=stoich,
            note=(
                "Forecast. Cut survival (C3P1_DetA_cuteff) times band acceptance "
                "(eff_AR). Resolution is already encoded in the published cut-survival "
                "curve, so no extra Gaussian smear is applied. Not a measured CRESST result."
            ),
            neutrino_events_per_ty={el: float(phi_el[el].sum()) for el in phi_el},
            untagged_events_per_ty=float(phi_untagged.sum()),
            bin_edges_keV=edges_c.tolist(),
        ),
        joint=joint,
        vmin_overlap_at_mass=dict(mass=m_star, xenon_vmin_ROI_kms=[float(vmin_xe[0]), float(vmin_xe[1])], bins=overlap),
    )
    out_path = OUT / "summary.json"
    # json can't hold numpy types; the dict was built from python scalars, but scan once.
    def sanitize(obj):
        if isinstance(obj, dict):
            return {k: sanitize(v) for k, v in obj.items()}
        if isinstance(obj, (list, tuple)):
            return [sanitize(v) for v in obj]
        if isinstance(obj, (np.floating,)):
            return float(obj)
        if isinstance(obj, (np.integer,)):
            return int(obj)
        if isinstance(obj, np.ndarray):
            return obj.tolist()
        return obj

    out_path.write_text(json.dumps(sanitize(summary), indent=2))
    print(f"Wrote {out_path}", flush=True)


